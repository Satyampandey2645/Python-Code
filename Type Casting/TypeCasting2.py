# ----------------------------------- Explicit Typecasting (Explicit Type Conversion) -----------------------------------

# ----------------------------------------------------- Integer to Float ------------------------------------------------

a = 10
b = float(a)
print(b)  # 10.0
print(type(b))  # <class 'float'>

# ----------------------------------------------------- Float to Integer ------------------------------------------------

x = 12.8
y = int(x)
print(y)  # 12

# ----------------------------------------------------- String to Integer -----------------------------------------------

s = "100"
n = int(s)
print(n)  # 100

# ----------------------------------------------------- Integer to String -----------------------------------------------

num = 50
s = str(num)
print(s)  # 50
print(type(s))  # <class 'str'>

# ------------------------------------------------------- List to Tuple -------------------------------------------------

lst = [1, 2, 3]
t = tuple(lst)
print(t)  # (1, 2, 3)

# ------------------------------------------------------ String to List -------------------------------------------------

s = "python"
lst = list(s)
print(lst)  # ['p', 'y', 't', 'h', 'o', 'n']

# --------------------------------------------------- Using ord() and chr() ---------------------------------------------

print(ord('A'))  # 65 -> ASCII value
print(chr(65))   # A -> Character
