a = 5
b = 3

print("The value of", a, "+", b, "is", a+b)  # The value of 5 + 3 is 8
print("The value of", a, "-", b, "is", a-b)  # The value of 5 - 3 is 2
print("The value of", a, "*", b, "is", a*b)  # The value of 5 * 3 is 15
print("The value of", a, "/", b, "is", a/b)  # The value of 5 / 3 is 1.6666666666666667
print("The value of", a, "%", b, "is", a%b)  # The value of 5 % 3 is 2
print("The value of", a, "//", b, "is", a//b)  # The value of 5 // 3 is 1
print("The value of", a, "**", b, "is", a**b)  # The value of 5 ** 3 is 125