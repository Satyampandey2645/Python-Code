name = "Satyam"
age = 21

# f-string (Recommended)
print(f"My name is {name} and I am {age} years old")  # My name is Satyam and I am 21 years old

# format() Method
print("My name is {} and age is {}".format("Satyam", 21))  # My name is Satyam and age is 21

# Old Style Formatting
print("Age is %d" % 21)  # Age is 21